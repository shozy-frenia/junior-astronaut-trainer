  /* =====================================================================
     Live DONKI. Turns raw DONKI API JSON into the SAME row shapes as the
     archive, so the engine does not care where the rows came from.
     The browser does the fetching (index.html); this file never touches the
     network. Shapes checked against the real API on 2026-11-14.
     ===================================================================== */
  var LIVE_DAYS = 30;
  function idFromLink(link, kind) {
    var m = new RegExp('/' + kind + '/(\\d+)/').exec(String(link || ''));
    return m ? Number(m[1]) : null;
  }
  function names(list) {                       // instruments: [{displayName}] (strings tolerated)
    return (list || []).map(function (i) { return typeof i === 'string' ? i : (i && i.displayName); }).filter(Boolean);
  }
  function cmeSpeed(c) {
    var list = c.cmeAnalyses || [], a = list.filter(function (x) { return x && x.isMostAccurate; })[0] || list[0];
    return a ? Number(a.speed) : NaN;
  }
  function marsImpact(c) {                     // first Mars hit DONKI models, most accurate analysis first
    var hit = null;
    (c.cmeAnalyses || []).slice().sort(function (a, b) { return (b && b.isMostAccurate ? 1 : 0) - (a && a.isMostAccurate ? 1 : 0); }).forEach(function (a) {
      ((a && a.enlilList) || []).forEach(function (run) {
        ((run && run.impactList) || []).forEach(function (imp) {
          if (!hit && imp && imp.location === 'Mars' && imp.arrivalTime) { hit = imp; }
        });
      });
    });
    return hit;
  }
  function liveRows(raw, fetched) {
    var seen = {}, rows = { flares: [], cmes: [], seps: [] };
    function fresh(kind, id) { var k = kind + id; if (seen[k]) { return false; } seen[k] = true; return true; }
    raw.FLR.forEach(function (f) {
      if (!f) { return; }
      var cls = String(f.classType || ''), id = idFromLink(f.link, 'FLR'), t = f.peakTime || f.beginTime, letter = cls.charAt(0);
      if (!/^[CMX]\d+(\.\d+)?$/.test(cls) || !id || !t || !fresh('FLR', id)) { return; }     // same cut as the archive: C, M, X only
      rows.flares.push(ent(cls, 'GOES X-ray class', SRC.donki, donkiLink('FLR', id), {
        retrieved: fetched, date: t, id: id, letter: letter,
        peakFluxWm2: Number((FLUX_BASE[letter] * parseFloat(cls.slice(1))).toPrecision(3))
      }));
    });
    raw.CME.forEach(function (c) {
      if (!c) { return; }
      var id = idFromLink(c.link, 'CME'), speed = cmeSpeed(c), hit = marsImpact(c);
      if (!id || !c.startTime || !(speed > 0) || !(hit || speed >= 1000) || !fresh('CME', id)) { return; }   // same cut as the archive
      rows.cmes.push(ent(speed, 'km/s', SRC.donki, donkiLink('CME', id), {
        retrieved: fetched, date: c.startTime, id: id,
        marsArrivalEstimate: hit ? hit.arrivalTime : null, glancingBlow: !!(hit && hit.isGlancingBlow)
      }));
    });
    raw.SEP.forEach(function (e) {
      if (!e) { return; }
      var id = idFromLink(e.link, 'SEP'), n = names(e.instruments), real = n.filter(function (x) { return !/^MODEL/.test(x); })[0];
      if (!id || !e.eventTime || !n.length || !fresh('SEP', id)) { return; }
      rows.seps.push(ent(real || n[0], 'detector and energy channel that saw the particles', SRC.donki, donkiLink('SEP', id), {
        retrieved: fetched, date: e.eventTime, id: id,
        linkedEvents: (e.linkedEvents || []).map(function (l) { return typeof l === 'string' ? l : (l && l.activityID); }).filter(Boolean)
      }));
    });
    return rows;
  }

  D.live = {
    days: LIVE_DAYS,
    window: function (today) { return { start: addDays(today, 1 - LIVE_DAYS), end: today }; },
    urlFor: function (kind, win) { return D.donki.api.base + kind + '?startDate=' + win.start + '&endDate=' + win.end; },
    // raw = { FLR: [...], CME: [...], SEP: [...] } exactly as the API returned them; today = 'YYYY-MM-DD' (UTC)
    // Returns a full copy of this data object with the live rows in it, or null if the answer cannot be trusted.
    build: function (raw, today) {
      if (!raw || !Array.isArray(raw.FLR) || !Array.isArray(raw.CME) || !Array.isArray(raw.SEP)) { return null; }
      if (!/^\d{4}-\d{2}-\d{2}$/.test(today) || today < RETRIEVED) { return null; }     // a clock earlier than the archive is wrong
      var win = D.live.window(today), rows = liveRows(raw, today), live = Object.assign({}, D);
      if (!rows.flares.length && !rows.cmes.length && !rows.seps.length) { return null; } // 30 empty days is more likely an outage
      live.donki = Object.assign({}, D.donki, { window: win, flares: rows.flares, cmes: rows.cmes, seps: rows.seps });
      live.counts = { flares: rows.flares.length, cmes: rows.cmes.length, seps: rows.seps.length };
      live.meta = Object.assign({}, D.meta, {
        mode: 'live', fetched: today, window: win,
        sourceLabel: 'LIVE NASA data (fetched ' + today + ')',
        notLive: 'Space weather is LIVE from NASA DONKI (fetched ' + today + '). It shows the last ' + LIVE_DAYS + ' days. Everything else is a saved copy from ' + RETRIEVED + ', not live.'
      });
      return live;
    }
  };

